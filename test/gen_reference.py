"""Generate `reference_values.csv` for the TenferroSci.jl test suite.

Run from the repository root:

    uv run test/gen_reference.py

Every value is computed with mpmath at 120 decimal digits. The arguments are
written as Python's shortest round-tripping `float` repr, so Julia parses them
back to exactly the same `Float64`. The double-double path is checked at those
same `f64` arguments.

The table is deliberately small: it is a regression net for the FFI boundary
(argument order, `hi`/`lo` packing), not a replacement for the upstream test
suite of tenferro-sci-rs, which validates the algorithms themselves against
xsref and mpmath.
"""

from __future__ import annotations

import mpmath as mp

mp.mp.dps = 120

# (function, [(arg1, arg2_or_None), ...])
CASES = {
    "gamma": [0.5, 2.5, 10.0, -0.5, -2.5, 1e-3, 171.0],
    "lgamma": [0.5, 2.5, 10.0, -0.5, -2.5, 1e-3, 171.0],
    "gammasgn": [-0.5, -1.5, 2.5, -2.5],
    "rgamma": [0.5, 2.5, -3.0, 10.0, 171.0],
    "digamma": [0.5, 2.5, 10.0, -0.5, -2.5],
    "zeta": [(2.0, 1.0), (3.0, 1.0), (0.5, 1.0), (-1.0, 1.0), (2.0, 2.0), (3.0, 0.5)],
    "beta": [(2.0, 3.0), (0.5, 0.5), (10.0, 0.1), (-0.5, 2.5)],
    "lbeta": [(2.0, 3.0), (0.5, 0.5), (10.0, 0.1), (-0.5, 2.5)],
    "poch": [(3.0, 4.0), (0.5, 2.0), (-2.0, 3.0), (10.0, 0.5), (1e-3, 100.0)],
    "lgam1p": [1e-20, 0.5, 1e-3, -0.5, 0.25],
    "binom": [(10.0, 3.0), (0.5, 2.0), (1e-9, 0.5), (100.0, 50.0)],
    "zetac": [2.0, 10.0, 1.5, -1.0, -10.0, 200.0],
    "trigamma": [1.0, 2.5, 0.5, -0.5, -2.5],
    "digammainv": [0.1, -0.5, 2.0],
    "gen_harmonic": [(4.0, 1.0), (4.0, -1.0), (100.0, 2.0), (10.0, 0.5), (1e6, 1.5)],
    "stirling2": [(5.0, 3.0), (10.0, 7.0), (100.0, 50.0), (220.0, 7.0)],
}


def evaluate(name: str, a: float, b: float | None) -> mp.mpf:
    x = mp.mpf(a)
    y = mp.mpf(b) if b is not None else None
    if name == "gamma":
        return mp.gamma(x)
    if name == "lgamma":
        return mp.log(abs(mp.gamma(x)))
    if name == "gammasgn":
        return mp.sign(mp.gamma(x))
    if name == "rgamma":
        # mpmath defines 1/Γ at the poles as 0.
        return mp.rgamma(x)
    if name == "digamma":
        return mp.digamma(x)
    if name == "zeta":
        assert y is not None
        return mp.zeta(x, y)
    if name == "beta":
        assert y is not None
        return mp.beta(x, y)
    if name == "lbeta":
        assert y is not None
        return mp.log(abs(mp.beta(x, y)))
    if name == "poch":
        assert y is not None
        return mp.rf(x, y)
    if name == "lgam1p":
        return mp.log(abs(mp.gamma(1 + x)))
    if name == "binom":
        assert y is not None
        return mp.binomial(x, y)
    if name == "zetac":
        return mp.zeta(x) - 1
    if name == "trigamma":
        return mp.polygamma(1, x)
    if name == "digammainv":
        # ψ is increasing on x > 0; Newton from a point on the right branch.
        start = {0.1: 1.5, -0.5: 1.0, 2.0: 10.0}[a]
        return mp.findroot(lambda t: mp.digamma(t) - x, start, tol=mp.mpf("1e-100"))
    if name == "gen_harmonic":
        assert y is not None
        n = int(a)
        if y == 1:
            return mp.harmonic(n)
        # sum_{i=1}^n i^-a = zeta(a) - zeta(a, n + 1) for a > 1
        return mp.zeta(y) - mp.zeta(y, n + 1)
    if name == "stirling2":
        assert y is not None
        n, k = int(a), int(b)
        return mp.nsum(
            lambda j: (-1) ** (k - int(j)) * mp.binomial(k, j) * mp.mpf(j) ** n,
            [0, k],
        ) / mp.factorial(k)
    raise ValueError(name)


def main() -> None:
    lines = [
        "# Generated by test/gen_reference.py with mpmath "
        f"{mp.__version__} at {mp.mp.dps} decimal digits.",
        "# function,a,b,value  (b is empty for one-argument functions)",
    ]
    for name, cases in CASES.items():
        for case in cases:
            a, b = case if isinstance(case, tuple) else (case, None)
            value = evaluate(name, a, b)
            lines.append(
                f"{name},{a!r},{'' if b is None else repr(b)},{mp.nstr(value, 100)}"
            )
    out = __file__.rsplit("/", 1)[0] + "/reference_values.csv"
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 2} rows to {out}")


if __name__ == "__main__":
    main()
